#!/usr/bin/env node
// Vendors the Bad Cat sim, content and codec into the backend (GDD 13.4 Phase 2, same pattern as the Heist's
// catnip-heist/scripts/vendor-sim.mjs). `POST /user/catbassadors/live` with `type: 'BAD_CAT'` replays ranked runs
// with exactly this code, and `POST /badcat/room` checks player rooms with it, so the backend never re-implements
// a rule.
//
//   npm run vendor-sim          # rebuild backend/src/vendor/badcat-sim/
//   npm run vendor-sim:check    # CI: exit 1 when the vendored copy differs from a fresh build
//   npm run vendor-sim:check-remote -- <backend url>
//                               # deploy gate: exit 1 unless that backend serves this exact bundle
//                               # (GET /badcat/sim), so the game never goes live ahead of the backend
//
// 1. A Vite library build of src/server/index.ts (and everything it imports: sim, content with the baked rooms and
//    public/daily/index.json, codec, the editor's pure room check) into one ES module, unminified.
// 2. backend/src/vendor/badcat-sim/badcat-sim.bundle.ts behind `/* eslint-disable */` and `// @ts-nocheck`.
// 3. index.ts: the typed facade the backend imports.
// 4. badcat-sim.sha256.json: sha256 of the bundle and the facade, the sim version and the tool versions; the backend
//    spec re-hashes the files, so a hand edit of the vendored copy fails the backend tests too.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

process.env.NODE_ENV = 'production';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const repo = resolve(root, '..');
const entry = join(root, 'src', 'server', 'index.ts');
const outDir = join(repo, 'backend', 'src', 'vendor', 'badcat-sim');
const check = process.argv.includes('--check');
const remoteFlag = process.argv.indexOf('--check-remote');
const remote = remoteFlag >= 0 ? process.argv[remoteFlag + 1] || process.env.BADCAT_BACKEND_URL : undefined;

const sha256 = (text) => createHash('sha256').update(text).digest('hex');
const viteVersion = JSON.parse(readFileSync(join(root, 'node_modules', 'vite', 'package.json'), 'utf8')).version;

/** JSON modules as one `JSON.parse("...")` string each (thousands of object-literal lines slow the backend lint). */
function jsonAsStrings() {
  return {
    name: 'badcat-json-as-strings',
    enforce: 'pre',
    load(id) {
      const path = resolve(id.split('?')[0]);
      if (!path.endsWith('.json')) return null;
      const data = JSON.parse(readFileSync(path, 'utf8'));
      return { code: `const data = JSON.parse(${JSON.stringify(JSON.stringify(data))});\nexport default data;\n`, moduleType: 'js' };
    },
  };
}

export async function bundle() {
  const result = await build({
    configFile: false,
    mode: 'production',
    root,
    logLevel: 'silent',
    define: { 'import.meta.env': '{}' },
    plugins: [jsonAsStrings()],
    build: {
      write: false,
      emptyOutDir: false,
      minify: false,
      sourcemap: false,
      target: 'es2022',
      lib: { entry, formats: ['es'], fileName: () => 'badcat-sim.js' },
      rolldownOptions: { output: { codeSplitting: false }, treeshake: { moduleSideEffects: false } },
    },
  });
  const outputs = (Array.isArray(result) ? result : [result]).flatMap((r) => r.output);
  const chunks = outputs.filter((o) => o.type === 'chunk');
  if (chunks.length !== 1) throw new Error(`vendor-sim: expected one chunk, got ${chunks.length}`);
  const code = chunks[0].code;
  const bad = /import\.meta|\bimport\s*\(|\brequire\s*\(|\bwindow\.|\bdocument\.|localStorage|indexedDB|navigator\./.exec(code);
  if (bad) throw new Error(`vendor-sim: the bundle reaches for a browser or module-loader API (${bad[0]}); keep src/server pure`);
  if (/^\s*import\s/m.test(code)) throw new Error('vendor-sim: the bundle still imports a module');
  return { code, modules: Object.keys(chunks[0].modules).map((id) => relative(root, id).split('\\').join('/')).sort() };
}

const HEADER = [
  '/* eslint-disable */',
  '// @ts-nocheck',
  '// GENERATED by bad-cat/tools/vendor-sim.mjs from bad-cat/src/server/index.ts. Do not edit:',
  '// change the Bad Cat sources and run `npm run vendor-sim` in bad-cat/ (CI runs `vendor-sim:check`).',
  '',
].join('\n');

const facade = (bundleSha256, simVersion) => `/* eslint-disable */
// GENERATED by bad-cat/tools/vendor-sim.mjs. Do not edit; run \`npm run vendor-sim\` in bad-cat/.
//
// Typed facade over the vendored Bad Cat sim (GDD 13.4 Phase 2). The types mirror bad-cat/src/server/index.ts;
// backend/src/badcat/badcat-sim.spec.ts pins the behaviour.
import * as bundle from './badcat-sim.bundle';

const sim: any = bundle;

export type BadcatInputRun = [number, number, number, number];
export type BadcatVerifyCode = 'BADCAT_REPLAY_INVALID' | 'BADCAT_SIM_VERSION' | 'BADCAT_TRAILING_INPUT' | 'BADCAT_NO_SCORE';

export interface BadcatRunLogInput {
    dayNo: number;
    simVersion: number;
    runs: readonly (readonly number[])[];
    finalHash?: number;
    score?: number;
}

export interface BadcatVerifiedRun {
    ok: true;
    dayNo: number;
    roomId: string;
    label: string;
    score: number;
    stamp: 'perfect' | 'clean' | 'caught';
    rank: string;
    caught: boolean;
    ticks: number;
    maxCombo: number;
    targets: number;
    finalHash: number;
    hashMatch?: boolean;
    runs: BadcatInputRun[];
}

export interface BadcatRejectedRun {
    ok: false;
    code: BadcatVerifyCode;
    reason: string;
}

export type BadcatVerifyResult = BadcatVerifiedRun | BadcatRejectedRun;

export interface BadcatRoomCheck {
    ok: boolean;
    errors: string[];
    room?: {
        id: string;
        title: string;
        author: string;
        shell: number;
        props: number;
        ancestors: string[];
        gameplayHash: number;
        boss: boolean;
    };
    clear?: { ok: boolean; targets: number; score: number };
}

export const SIM_VERSION: number = sim.SIM_VERSION;
export const TICK_HZ: number = sim.TICK_HZ;
export const RUN_TICKS: number = sim.RUN_TICKS;
export const BOSS_TICKS: number = sim.BOSS_TICKS;
export const MAX_RUN_TICKS: number = sim.MAX_RUN_TICKS;
export const MAX_RUNS: number = sim.MAX_RUNS;
/** sha256 of badcat-sim.bundle.ts: which sim this backend replays with (GET /badcat/sim). */
export const BUNDLE_SHA256 = '${bundleSha256}';
/** The SIM_VERSION this bundle was built with (${simVersion}). */
export const BUNDLE_SIM_VERSION = ${simVersion};

export const verifyRanked: (log: unknown) => BadcatVerifyResult = sim.verifyRanked;
export const canonicalRuns: (runs: unknown) => BadcatInputRun[] | null = sim.canonicalRuns;
export const canonicalLogKey: (log: Pick<BadcatRunLogInput, 'dayNo' | 'simVersion' | 'runs'>) => string = sim.canonicalLogKey;
export const dayNoUtc: (ms: number) => number = sim.dayNoUtc;
export const dayTitle: (dayNo: number) => string = sim.dayTitle;
export const checkRoom: (code: unknown, clearRuns?: unknown) => BadcatRoomCheck = sim.checkRoom;
export const catCodeOk: (code: unknown) => boolean = sim.catCodeOk;
export const cleanName: (raw: unknown, max?: number) => string = sim.cleanName;
export const cleanTitle: (raw: unknown, max?: number) => string = sim.cleanTitle;
`;

async function main() {
  const { code, modules } = await bundle();
  const text = HEADER + code;
  const bundleSha = sha256(text);
  const simVersion = Number(/SIM_VERSION = (\d+)/.exec(readFileSync(join(root, 'src', 'types.ts'), 'utf8'))?.[1] ?? 0);
  const face = facade(bundleSha, simVersion);
  const info = JSON.stringify(
    { bundle: bundleSha, facade: sha256(face), simVersion, vite: viteVersion, modules: modules.length },
    null,
    2
  ) + '\n';
  const files = { 'badcat-sim.bundle.ts': text, 'index.ts': face, 'badcat-sim.sha256.json': info };

  if (remote) {
    const url = `${remote.replace(/\/+$/, '')}/badcat/sim`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`vendor-sim: ${url} answered ${res.status}`);
    const served = await res.json();
    if (served.bundle !== bundleSha) {
      console.error(`vendor-sim: ${url} serves bundle ${served.bundle}, this build is ${bundleSha}`);
      process.exit(1);
    }
    console.log(`vendor-sim: ${url} serves this sim (${bundleSha.slice(0, 12)})`);
    return;
  }
  if (check) {
    const drift = Object.entries(files).filter(([name, body]) => {
      const p = join(outDir, name);
      return !existsSync(p) || readFileSync(p, 'utf8') !== body;
    });
    if (drift.length) {
      console.error(`vendor-sim: backend/src/vendor/badcat-sim is stale (${drift.map(([n]) => n).join(', ')}); run npm run vendor-sim`);
      process.exit(1);
    }
    console.log('vendor-sim: backend copy is current');
    return;
  }
  mkdirSync(outDir, { recursive: true });
  for (const [name, body] of Object.entries(files)) writeFileSync(join(outDir, name), body);
  console.log(`vendor-sim: wrote ${relative(repo, outDir)} (${modules.length} modules, ${(text.length / 1024).toFixed(0)} KB, sha ${bundleSha.slice(0, 12)})`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  });
}
