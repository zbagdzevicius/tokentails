/**
 * The shipped room JSON and the schedule must equal the generators (authoring.ts, schedule.ts). To re-bake after
 * a deliberate change:
 *   BADCAT_WRITE_ROOMS=1 npx vitest run src/content/rooms.bake.test.ts
 * This writes rooms/daily-001..021.json and public/daily/index.json (days 1..63). The FROZEN rooms (The Glass,
 * kitchen-v1..7) are never rewritten: their hashes are pinned in content.test.ts. Hand-edited day fields in
 * index.json (community, sponsor) are kept when it is rewritten.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { buildKitchenRoom, GLASS_RECIPE, KITCHEN_RECIPES } from './authoring';
import { entryFor, roomForDay, scheduleHand } from './daily';
import { AUTHORED_DAYS, DAY1, INDEX_DAYS, generateRoom } from './schedule';
import type { RoomDef } from '../types';

const here = dirname(fileURLToPath(import.meta.url));
const roomsDir = join(here, 'rooms');
const dailyIndex = join(here, '..', '..', 'public', 'daily', 'index.json');
const WRITE = process.env.BADCAT_WRITE_ROOMS === '1';

const dayId = (n: number): string => `daily-${String(n).padStart(3, '0')}`;

function authoredRooms(): Record<string, RoomDef> {
  const out: Record<string, RoomDef> = {};
  // the first attempt that validates, like every generated day (round 2: the new room rules made one retry useful)
  for (let n = 1; n <= AUTHORED_DAYS; n++) out[dayId(n)] = generateRoom(n);
  return out;
}

function dailyIndexJson(rooms: Record<string, RoomDef>): unknown {
  const days = [];
  for (let n = 1; n <= INDEX_DAYS; n++) {
    const base = n <= AUTHORED_DAYS ? rooms[dayId(n)] : generateRoom(n);
    days.push(entryFor(n, roomForDay(n, scheduleHand(n), base)));
  }
  return {
    version: 2,
    day1: DAY1,
    note: 'Generated by src/content/rooms.bake.test.ts (BADCAT_WRITE_ROOMS=1). Hand-edit only `community` {code,title,author} (Sundays from day 21) and `sponsor` {label,url,brandShelf}; both survive a re-bake.',
    glass: 'glass',
    authored: AUTHORED_DAYS,
    days,
  };
}

const stringify = (v: unknown): string => JSON.stringify(v, null, 2) + '\n';

describe('baked rooms', () => {
  const rooms = authoredRooms();
  if (WRITE) {
    it('writes rooms/daily-*.json and public/daily/index.json', () => {
      for (const [id, r] of Object.entries(rooms)) writeFileSync(join(roomsDir, `${id}.json`), stringify(r));
      writeFileSync(dailyIndex, stringify(dailyIndexJson(rooms)));
    });
    return;
  }
  it('the frozen Kitchen variants and The Glass still equal their generator', () => {
    const frozen: Record<string, RoomDef> = { glass: buildKitchenRoom(GLASS_RECIPE) };
    for (const r of KITCHEN_RECIPES) frozen[r.id] = buildKitchenRoom(r);
    for (const [id, r] of Object.entries(frozen)) expect(JSON.parse(readFileSync(join(roomsDir, `${id}.json`), 'utf8')), id).toEqual(JSON.parse(JSON.stringify(r)));
  });
  for (const [id, r] of Object.entries(rooms)) {
    it(`rooms/${id}.json equals the generator`, () => {
      expect(JSON.parse(readFileSync(join(roomsDir, `${id}.json`), 'utf8'))).toEqual(JSON.parse(JSON.stringify(r)));
    });
  }
  it('public/daily/index.json equals the schedule (days 1..63)', () => {
    expect(JSON.parse(readFileSync(dailyIndex, 'utf8'))).toEqual(JSON.parse(JSON.stringify(dailyIndexJson(rooms))));
  });
});
