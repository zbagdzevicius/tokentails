#!/usr/bin/env node
/**
 * npm run gen:skins (GDD §7.2 card skins): the per-family palette table `src/render/skins/families.gen.ts`, read from
 * the 58 local base sheets in `client/public/heist-game/assets/cats/*.png` with the shared classifier
 * (src/render/skins/classify.ts, imported directly: Node strips its types). Offline, no dependencies (tools/lib/png.mjs).
 *
 *   node tools/gen-cat-skins.mjs            write the table (and a contact sheet when --sheet <png> is given)
 *   node tools/gen-cat-skins.mjs --check    exit 1 when the committed table differs from a fresh run
 *
 * Local file names are not always the CDN folder names: `ALIAS` maps them (the rest is the upper-cased name).
 * `OBISDIAN` (a CDN folder with no base sheet) reads the OBSIDIAN row at runtime (render/skins/registry.ts).
 * `render/skins/overrides.json` (keyed by family) is merged on top at runtime, never here.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { decodePng, encodePng } from './lib/png.mjs';
import { classifySprite, rowOf, sheetFrames } from '../src/render/skins/classify.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SHEETS = path.resolve(ROOT, '..', 'client', 'public', 'heist-game', 'assets', 'cats');
const OUT = path.join(ROOT, 'src', 'render', 'skins', 'families.gen.ts');

/** Local sheet name → CDN folder (`assets/<FOLDER>/<variant>.png`). */
export const ALIAS = Object.freeze({
  peachies: 'PEACHES',
  eldrem: 'ELDREM',
  raccon: 'RACCON',
  'solo-survivor': 'SOLO-SURVIVOR',
  savanhan: 'SAVANHAN',
  obi: 'OBI',
});

/** Not cats, or art the classifier cannot read (333 colours): solid coats from the extracted colours. */
export const OUTLIERS = Object.freeze(['AMBERCLAW', 'BEAVER', 'FOX', 'GOAT', 'OWL', 'YAK', 'MOOSE', 'RACCON', 'ELDREM', 'SOLO-SURVIVOR', 'STICKY', 'HANA']);

const hex = (n) => `0x${n.toString(16).padStart(6, '0')}`;

export function generate() {
  const rows = {};
  const sheets = {};
  for (const file of fs.readdirSync(SHEETS).filter((f) => f.endsWith('.png')).sort()) {
    const local = file.slice(0, -4);
    const family = ALIAS[local] ?? local.toUpperCase();
    const sheet = decodePng(fs.readFileSync(path.join(SHEETS, file)));
    const c = classifySprite(sheetFrames(sheet), { outlier: OUTLIERS.includes(family) });
    rows[family] = rowOf(c);
    sheets[family] = sheet;
  }
  return { rows, sheets };
}

export function render(rows) {
  const keys = Object.keys(rows).sort();
  const line = (k) => {
    const r = rows[k];
    const parts = [`p: '${r.pattern}'`, `b: ${hex(r.base)}`, `d: ${hex(r.deep)}`, `l: ${hex(r.light)}`, `c: ${hex(r.cream)}`];
    if (r.patch !== undefined) parts.push(`x: ${hex(r.patch)}`);
    parts.push(`e: ${hex(r.eyes)}`, `n: ${hex(r.nose)}`, `i: ${hex(r.earInner)}`, `k: ${r.confidence}`);
    return `  '${k}': { ${parts.join(', ')} },`;
  };
  return `// GENERATED by tools/gen-cat-skins.mjs from client/public/heist-game/assets/cats/*.png. Do not edit by hand:
// fix a misread family in render/skins/overrides.json, or the classifier, and run \`npm run gen:skins\`.
/**
 * Card skin palettes per Token Tails breed folder (\`assets/<FAMILY>/<variant>.png\`), compact keys: p pattern,
 * b base, d deep, l light, c cream, x patch, e eyes, n nose, i inner ear, k classifier confidence.
 */
import type { SkinPattern } from './classify';

export interface FamilyRow {
  p: SkinPattern;
  b: number;
  d: number;
  l: number;
  c: number;
  x?: number;
  e: number;
  n: number;
  i: number;
  k: number;
}

export const FAMILIES: Readonly<Record<string, FamilyRow>> = {
${keys.map(line).join('\n')}
};
`;
}

/** A contact sheet: per family the IDLE frame 0 (×4) next to swatches of base, deep, light, cream, patch, eyes, nose, ear. */
function contactSheet(rows, sheets, file) {
  const keys = Object.keys(rows).sort();
  const cols = 4;
  const cw = 48 * 4 + 8 * 18 + 16;
  const ch = 48 * 4 + 8;
  const W = cw * cols;
  const H = ch * Math.ceil(keys.length / cols);
  const out = new Uint8Array(W * H * 4).fill(235);
  const put = (x, y, rgb) => {
    if (x < 0 || y < 0 || x >= W || y >= H) return;
    const o = (y * W + x) * 4;
    out[o] = (rgb >> 16) & 255;
    out[o + 1] = (rgb >> 8) & 255;
    out[o + 2] = rgb & 255;
    out[o + 3] = 255;
  };
  keys.forEach((k, n) => {
    const ox = (n % cols) * cw;
    const oy = Math.floor(n / cols) * ch;
    const s = sheets[k];
    for (let y = 0; y < 48; y++)
      for (let x = 0; x < 48; x++) {
        const i = ((4 * 48 + y) * s.width + x) * 4;
        const c = s.data[i + 3] ? (s.data[i] << 16) | (s.data[i + 1] << 8) | s.data[i + 2] : (x + y) & 1 ? 0xd0d0d0 : 0xf0f0f0;
        for (let dy = 0; dy < 4; dy++) for (let dx = 0; dx < 4; dx++) put(ox + x * 4 + dx, oy + y * 4 + dy, c);
      }
    const r = rows[k];
    const sw = [r.base, r.deep, r.light, r.cream, r.patch ?? 0xeeeeee, r.eyes, r.nose, r.earInner];
    sw.forEach((c, i) => {
      for (let dy = 0; dy < 36; dy++) for (let dx = 0; dx < 16; dx++) put(ox + 48 * 4 + 8 + i * 18 + dx, oy + 20 + dy, c);
    });
    // pattern marker bar: one colour per pattern
    const pc = { solid: 0x999999, tabby: 0xc07a2a, points: 0x2a6fc0, spots: 0x8a2ac0, tuxedo: 0x111111, calico: 0xe0602a }[r.pattern];
    for (let dy = 0; dy < 10; dy++) for (let dx = 0; dx < 8 * 18; dx++) put(ox + 48 * 4 + 8 + dx, oy + 70 + dy, pc);
    const conf = Math.round(r.confidence * 8 * 18);
    for (let dy = 0; dy < 6; dy++) for (let dx = 0; dx < conf; dx++) put(ox + 48 * 4 + 8 + dx, oy + 86 + dy, 0x2a9a4a);
  });
  fs.writeFileSync(file, encodePng(W, H, out));
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const { rows, sheets } = generate();
  const text = render(rows);
  const sheetAt = process.argv.indexOf('--sheet');
  if (sheetAt > 0 && process.argv[sheetAt + 1]) contactSheet(rows, sheets, process.argv[sheetAt + 1]);
  if (process.argv.includes('--print')) for (const [k, r] of Object.entries(rows)) console.log(k.padEnd(14), r.pattern.padEnd(7), r.confidence, hex(r.base), hex(r.deep), hex(r.cream), r.patch !== undefined ? hex(r.patch) : '-', 'eyes', hex(r.eyes));
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) {
      console.error('families.gen.ts is out of date: run npm run gen:skins');
      process.exit(1);
    }
    console.log(`families.gen.ts up to date (${Object.keys(rows).length} families)`);
  } else if (!process.argv.includes('--print')) {
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${path.relative(ROOT, OUT)} (${Object.keys(rows).length} families, ${text.length} bytes)`);
  }
}
