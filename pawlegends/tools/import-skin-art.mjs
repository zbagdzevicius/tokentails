#!/usr/bin/env node
/**
 * Imports the brand-book champion and skin art (Gemini, v6 Lightning Rivalry skins library) as game-ready files.
 *
 *   node tools/import-skin-art.mjs <brandbook skins/img dir>
 *
 * Reads `base-<hero>-portrait.webp` (512² head crop) and `skin-<skin id>.webp` (1080×1350 splash) +
 * `skin-<skin id>-portrait.webp` (512²), and writes (webp q78, `cwebp` on PATH):
 * - `public/assets/faces/<hero>-256.webp`: every hero's face, in the game bundle (≈7 KB each; the HUD, pick tiles,
 *   cards and avatars use it, offline too)
 * - `../pawlegends-web/public/pawlegends-art/skins/<skin id>-256.webp | -360.webp | -720.webp`: the skin face and
 *   the 4:5 skin splash at 360 and 720 px wide. Served by pawlegends.app beside the game, OUTSIDE the 10 MB game
 *   budget, loaded lazily (src/ui/art.ts); a missing file falls back to the hero's face or splash.
 * - `src/ui/art/skinArt.gen.ts`: the skin ids that have art (the UI asks for remote art only for these).
 *
 * Idempotent: it rewrites every output. Run it again when the brand book adds or regenerates art.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2];
if (!src || !fs.existsSync(src)) {
  console.error('usage: node tools/import-skin-art.mjs <brandbook skins/img dir>');
  process.exit(2);
}
const FACES = path.join(PKG, 'public/assets/faces');
const SKINS = path.resolve(PKG, '../pawlegends-web/public/pawlegends-art/skins');
const GEN = path.join(PKG, 'src/ui/art/skinArt.gen.ts');
for (const d of [FACES, SKINS, path.dirname(GEN)]) fs.mkdirSync(d, { recursive: true });

const webp = (input, out, w, h) => execFileSync('cwebp', ['-quiet', '-q', '78', '-m', '6', '-resize', String(w), String(h), input, '-o', out]);

const files = fs.readdirSync(src);
const heroes = files.filter((f) => /^base-[a-z]+-portrait\.webp$/.test(f)).map((f) => f.slice(5, -14)).sort();
for (const h of heroes) webp(path.join(src, `base-${h}-portrait.webp`), path.join(FACES, `${h}-256.webp`), 256, 256);

const skins = files
  .filter((f) => f.startsWith('skin-') && f.endsWith('.webp') && !f.endsWith('-portrait.webp'))
  .map((f) => f.slice(5, -5))
  .filter((id) => /^[a-z0-9._-]+$/.test(id) && files.includes(`skin-${id}-portrait.webp`))
  .sort();
for (const id of skins) {
  webp(path.join(src, `skin-${id}-portrait.webp`), path.join(SKINS, `${id}-256.webp`), 256, 256);
  webp(path.join(src, `skin-${id}.webp`), path.join(SKINS, `${id}-360.webp`), 360, 450);
  webp(path.join(src, `skin-${id}.webp`), path.join(SKINS, `${id}-720.webp`), 720, 900);
}

fs.writeFileSync(
  GEN,
  `// Generated by tools/import-skin-art.mjs from the brand-book skins library. Do not edit by hand.\n` +
    `/** Skin ids (coat / skin item ids) with painted art in pawlegends-web/public/pawlegends-art/skins/. */\n` +
    `export const SKIN_ART_IDS: ReadonlySet<string> = new Set([\n${skins.map((s) => `  '${s}',`).join('\n')}\n]);\n`,
);
const size = (dir) => fs.readdirSync(dir).reduce((s, f) => s + fs.statSync(path.join(dir, f)).size, 0);
console.log(`faces ${heroes.length} (${(size(FACES) / 1000).toFixed(0)} KB in the bundle), skins ${skins.length} (${(size(SKINS) / 1e6).toFixed(2)} MB on pawlegends.app)`);
