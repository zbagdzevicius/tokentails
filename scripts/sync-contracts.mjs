#!/usr/bin/env node
/**
 * Copies the framework-free contracts in `shared/` into each package (plan F2).
 *
 *   node scripts/sync-contracts.mjs           write every generated copy whose content changed
 *   node scripts/sync-contracts.mjs --check   write nothing; exit 1 if any copy is missing or stale
 *
 * `shared/manifest.json` maps each shared file to the packages that receive it. Every copy starts
 * with a GENERATED header. Only files whose content differs are written, so parallel work on
 * different shared files never clobbers each other, and an unchanged tree is left byte-for-byte
 * alone (watchers do not restart). A generated file that the manifest no longer produces is
 * reported as drift, and removed in write mode.
 *
 * No dependencies: runs on the Node that ships with any package in this repo.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const GENERATED_MARKER = 'GENERATED by scripts/sync-contracts.mjs';

const DEFAULT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** The header written at the top of every generated copy. */
export function header(sourcePath) {
    return (
        `// ${GENERATED_MARKER} from shared/${sourcePath}. Do not edit this copy:\n` +
        `// edit shared/${sourcePath}, then run \`node scripts/sync-contracts.mjs\`.\n`
    );
}

export function loadManifest(root) {
    const path = join(root, 'shared', 'manifest.json');
    const manifest = JSON.parse(readFileSync(path, 'utf8'));
    if (!manifest || typeof manifest.targets !== 'object' || typeof manifest.files !== 'object') {
        throw new Error(`${path}: expected { targets, files }`);
    }
    for (const [file, targets] of Object.entries(manifest.files)) {
        if (!Array.isArray(targets) || targets.length === 0) {
            throw new Error(`${path}: "${file}" needs a non-empty target list`);
        }
        if (file.includes('..') || file.startsWith('/')) {
            throw new Error(`${path}: "${file}" must be a path inside shared/`);
        }
        for (const target of targets) {
            if (!manifest.targets[target]) {
                throw new Error(`${path}: "${file}" names unknown target "${target}"`);
            }
        }
    }
    return manifest;
}

/** Relative imports (`from './enums'`) of a shared source, as manifest paths (`enums.ts`). */
export function relativeImports(sourcePath, content) {
    const found = [];
    const pattern = /(?:from|import)\s*\(?\s*['"](\.{1,2}\/[^'"]+)['"]/g;
    let match;
    while ((match = pattern.exec(content))) {
        const joined = posix.normalize(posix.join(posix.dirname(sourcePath), match[1]));
        found.push(joined.endsWith('.ts') ? joined : `${joined}.ts`);
    }
    return found;
}

/** In-flight `writeAtomic` temp files. Another run may be about to rename one, so never touch them. */
const isTempFile = name => name.endsWith('.tmp');

function walk(dir) {
    if (!existsSync(dir)) {
        return [];
    }
    const out = [];
    for (const entry of readdirSync(dir)) {
        if (isTempFile(entry)) {
            continue;
        }
        const full = join(dir, entry);
        let stats;
        try {
            stats = statSync(full);
        } catch (error) {
            // Removed or renamed by a concurrent run between readdir and stat.
            if (error.code === 'ENOENT') {
                continue;
            }
            throw error;
        }
        if (stats.isDirectory()) {
            out.push(...walk(full));
        } else {
            out.push(full);
        }
    }
    return out;
}

/** Plans every generated file: `{ target, path, content }` plus problems found in the manifest. */
export function plan(root) {
    const manifest = loadManifest(root);
    const outputs = [];
    const pending = [];
    const errors = [];
    const sharedDir = join(root, 'shared');

    const listed = new Set(Object.keys(manifest.files));
    for (const file of walk(sharedDir)) {
        const rel = relative(sharedDir, file).split(sep).join('/');
        if (rel.endsWith('.ts') && !listed.has(rel)) {
            errors.push(`shared/${rel} is not listed in shared/manifest.json`);
        }
    }

    for (const [file, targets] of Object.entries(manifest.files)) {
        const source = join(sharedDir, file);
        if (!existsSync(source)) {
            pending.push(file);
            continue;
        }
        const body = readFileSync(source, 'utf8');
        for (const dependency of relativeImports(file, body)) {
            const dependencyTargets = manifest.files[dependency];
            for (const target of targets) {
                if (!dependencyTargets || !dependencyTargets.includes(target)) {
                    errors.push(`shared/${file} imports ${dependency}, which is not copied to "${target}"`);
                }
            }
        }
        for (const target of targets) {
            outputs.push({
                target,
                path: join(root, manifest.targets[target], file),
                content: header(file) + body,
            });
        }
    }

    const expected = new Set(outputs.map(output => output.path));
    const orphans = [];
    for (const dir of Object.values(manifest.targets)) {
        for (const file of walk(join(root, dir))) {
            if (expected.has(file)) {
                continue;
            }
            const text = readFileSync(file, 'utf8');
            if (text.includes(GENERATED_MARKER)) {
                orphans.push(file);
            }
        }
    }

    return { outputs, orphans, pending, errors };
}

function writeAtomic(path, content) {
    mkdirSync(dirname(path), { recursive: true });
    const temp = `${path}.${process.pid}.tmp`;
    writeFileSync(temp, content);
    renameSync(temp, path);
}

/**
 * Syncs (or checks) the generated copies under `root`.
 * Returns `{ ok, written, removed, stale, pending, errors }`; paths are relative to `root`.
 */
export function sync({ root = DEFAULT_ROOT, check = false } = {}) {
    const { outputs, orphans, pending, errors } = plan(root);
    const rel = path => relative(root, path).split(sep).join('/');
    const stale = [];
    const written = [];
    const removed = [];

    for (const output of outputs) {
        const current = existsSync(output.path) ? readFileSync(output.path, 'utf8') : null;
        if (current === output.content) {
            continue;
        }
        stale.push(rel(output.path));
        if (!check && errors.length === 0) {
            writeAtomic(output.path, output.content);
            written.push(rel(output.path));
        }
    }
    for (const orphan of orphans) {
        stale.push(rel(orphan));
        if (!check && errors.length === 0) {
            rmSync(orphan);
            removed.push(rel(orphan));
        }
    }

    const ok = errors.length === 0 && (check ? stale.length === 0 : true);
    return { ok, written, removed, stale, pending, errors };
}

const USAGE = 'usage: node scripts/sync-contracts.mjs [--check] [--root <dir>]';

/** Parses the CLI arguments. Returns `{ error }` for a missing `--root` value or an unknown argument. */
export function parseArgs(argv) {
    let check = false;
    let root = DEFAULT_ROOT;
    for (let index = 0; index < argv.length; index += 1) {
        const arg = argv[index];
        if (arg === '--check') {
            check = true;
        } else if (arg === '--root') {
            const value = argv[index + 1];
            if (!value || value.startsWith('--')) {
                return { error: '--root needs a directory' };
            }
            root = resolve(value);
            index += 1;
        } else {
            return { error: `unknown argument: ${arg}` };
        }
    }
    return { check, root };
}

function main(argv) {
    const args = parseArgs(argv);
    if (args.error) {
        console.error(`error: ${args.error}`);
        console.error(USAGE);
        return 2;
    }
    const { check, root } = args;
    const result = sync({ root, check });

    for (const error of result.errors) {
        console.error(`error: ${error}`);
    }
    if (result.pending.length) {
        console.log(`pending (listed, not created yet): ${result.pending.join(', ')}`);
    }
    if (check) {
        if (result.stale.length) {
            console.error('Generated contracts are out of date. Run `node scripts/sync-contracts.mjs`:');
            result.stale.forEach(path => console.error(`  ${path}`));
        } else if (result.ok) {
            console.log('Generated contracts are up to date.');
        }
    } else {
        result.written.forEach(path => console.log(`wrote ${path}`));
        result.removed.forEach(path => console.log(`removed ${path}`));
        if (result.ok && !result.written.length && !result.removed.length) {
            console.log('Generated contracts already up to date.');
        }
    }
    return result.ok ? 0 : 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
    process.exitCode = main(process.argv.slice(2));
}
