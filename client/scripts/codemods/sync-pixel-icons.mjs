#!/usr/bin/env node
/**
 * Code generator for PixelIcon (plan F3.6, decision #63).
 *
 *   node scripts/codemods/sync-pixel-icons.mjs                 # reads node_modules/pixelarticons
 *   node scripts/codemods/sync-pixel-icons.mjs --from <dir>    # reads <dir>/svg/*.svg
 *   node scripts/codemods/sync-pixel-icons.mjs --check         # exit 1 if the output is stale
 *
 * Copies the path data of the glyphs listed in ICONS from pixelarticons (MIT)
 * into components/shared/icons/pixelarticons.ts. PixelIcon renders them as
 * inline SVG, so the app ships only the glyphs it uses and needs no SVG loader,
 * and the jest/Next builds do not depend on the package's ESM React entry.
 *
 * To add an icon: add its pixelarticons name to ICONS and rerun. Glyphs the set
 * does not have are hand-drawn in components/shared/icons/custom.ts instead.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const CLIENT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = path.join(CLIENT_ROOT, "components/shared/icons/pixelarticons.ts");

/** pixelarticons names the app uses. Keep sorted. */
export const ICONS = [
  "apple",
  "avatar-circle",
  "bookmark",
  "check",
  "chevron-left",
  "chevron-right",
  "close",
  "copy",
  "external-link",
  "eye",
  "eye-off",
  "facebook",
  "heart",
  "key",
  "loader",
  "lock",
  "mail",
  "send",
  "share",
  "thumbs-up",
  "user",
];

const args = process.argv.slice(2);
const fromIdx = args.indexOf("--from");
const pkgDir = fromIdx >= 0 ? path.resolve(args[fromIdx + 1]) : path.join(CLIENT_ROOT, "node_modules/pixelarticons");
const check = args.includes("--check");

const pkgJsonPath = path.join(pkgDir, "package.json");
if (!fs.existsSync(pkgJsonPath)) {
  // pixelarticons is installed by task 1c; without it there is nothing to sync against.
  console.error(`pixelarticons not installed (task 1c); run after install. Looked in ${pkgDir}`);
  process.exit(2);
}
const pkg = JSON.parse(fs.readFileSync(pkgJsonPath, "utf8"));
if (pkg.name !== "pixelarticons") throw new Error(`${pkgDir} is not the pixelarticons package`);
if (pkg.license && pkg.license !== "MIT") throw new Error(`pixelarticons license is ${pkg.license}, expected MIT`);

const entries = ICONS.map((name) => {
  const file = path.join(pkgDir, "svg", `${name}.svg`);
  if (!fs.existsSync(file)) throw new Error(`pixelarticons has no "${name}" glyph; hand-draw it in icons/custom.ts`);
  const svg = fs.readFileSync(file, "utf8");
  if (!/viewBox="0 0 24 24"/.test(svg)) throw new Error(`${name}.svg is not on the 24x24 grid`);
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`${name}.svg has no <path d>`);
  return `  "${name}": ${JSON.stringify(paths)},`;
});

const output = `// Generated by scripts/codemods/sync-pixel-icons.mjs from pixelarticons ${pkg.version}.
// Do not edit by hand; add names to ICONS in that script and rerun it.
//
// pixelarticons, MIT License, Copyright (c) 2019 Gerrit Halfmann.
// https://github.com/halfmage/pixelarticons

/** Path data on a 24x24 grid, filled with currentColor. */
export const PIXELARTICONS = {
${entries.join("\n")}
} as const satisfies Record<string, readonly string[]>;
`;

if (check) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== output) {
    console.error(`${path.relative(CLIENT_ROOT, OUT)} is stale; run scripts/codemods/sync-pixel-icons.mjs`);
    process.exit(1);
  }
  console.log("pixel icons up to date");
} else {
  fs.writeFileSync(OUT, output);
  console.log(`wrote ${ICONS.length} glyphs to ${path.relative(CLIENT_ROOT, OUT)} (pixelarticons ${pkg.version})`);
}
