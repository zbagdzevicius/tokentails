import type * as THREE from 'three';

// ---------- ids ----------
export type LevelId = 'meowhattan' | 'docks' | 'suburbia' | 'nekotown' | 'base';
export type CatId = 'tabby' | 'chonk' | 'shadow' | 'siamese';
export type EnemyId = 'heli' | 'cannonTruck' | 'cucumberTower' | 'cucumberJet' | 'vacuum' | 'mechaDog' | 'roombaPrime';
export type UpgradeId = 'power' | 'speed' | 'fur' | 'ultra';
export const LEVEL_ORDER: readonly LevelId[] = ['meowhattan', 'docks', 'suburbia', 'nekotown', 'base'];
export const CAT_ORDER: readonly CatId[] = ['tabby', 'chonk', 'shadow', 'siamese'];
export const UPGRADE_IDS: readonly UpgradeId[] = ['power', 'speed', 'fur', 'ultra'];
export const ENEMY_IDS: readonly EnemyId[] = ['heli', 'cannonTruck', 'cucumberTower', 'cucumberJet', 'vacuum', 'mechaDog', 'roombaPrime'];

// ---------- world / city ----------
/** Look of a city. Applied by world/theme.ts applyTheme(). */
export interface CityTheme {
  sky: number;
  fogNear: number;
  fogFar: number;
  hemiSky: number;
  hemiGround: number;
  hemiIntensity: number;
  sunColor: number;
  sunIntensity: number;
  exposure: number;
  ground: number; // asphalt
  sidewalk: number;
  grass: number;
  dash: number; // road centre line
  palette: number[]; // building colours
  windowLit: number; // 0..1 share of lit windows (day ~0.18, night ~0.6)
  windowGlass: number; // unlit glass colour
  windowGlow: number; // lit window colour
  night: boolean;
  taxiColor: number;
  taxiShare: number; // 0..1
  carColors: number[];
}

/** Layout parameters of a city. Generated by world/city.ts City.build(). */
export interface WorldDef {
  seed: number;
  layout: 'downtown' | 'docks' | 'suburbia' | 'neon' | 'base';
  n: number; // blocks per side (<= 11; total segments <= CAPS.segs)
  block: number; // block pitch incl. street
  street: number; // street width
  parkChance: number;
  heightBase: number;
  heightRand: number;
  centreBoost: number;
  centreRand: number;
  valueBase: number; // $M per floor
  valueRand: number;
  theme: CityTheme;
}

// ---------- levels / objectives ----------
export type ObjectiveKind =
  | 'damage' // G.damage >= target ($M)
  | 'landmarks' // WANTED landmarks toppled >= target
  | 'kills' // kills of `enemy` (or of all enemies when omitted) >= target
  | 'patience' // patience at the end >= target (only counts if the level was finished, not on TOO WET)
  | 'destroyedPct' // % of the city's floors knocked off >= target
  | 'combo' // max combo >= target
  | 'fish' // fish trucks eaten >= target
  | 'buildings' // buildings wrecked >= target
  | 'boss'; // boss defeated (target 1)

export interface Objective {
  kind: ObjectiveKind;
  target: number;
  enemy?: EnemyId;
  label: string; // shown on the intro card and HUD, e.g. "Cause $500M damage"
}

/** How one enemy type appears in a level. Interpreted by that enemy type's own update(). */
export interface EnemySpec {
  type: EnemyId;
  delay: number; // seconds of play before the first spawn
  every: number; // seconds between spawns at the start
  minEvery: number; // spawn interval floor
  everyRamp: number; // interval shrinks by this many seconds per 10 s elapsed
  max: number; // alive at once at the start
  maxRamp: number; // +1 alive allowed every `maxRamp` seconds (0 = never)
  params?: Record<string, number>; // type specific tuning (speed, hp, damage...)
}

export interface MusicSpec {
  bpm: number;
  root: number; // MIDI note of the tonic
  scale: 'major' | 'minor' | 'dorian' | 'mixolydian' | 'pentatonic' | 'phrygian';
  style: 'swing' | 'surf' | 'suburb' | 'synthwave' | 'march' | 'boss';
}

export interface LevelDef {
  id: LevelId;
  index: number; // 0..4 campaign order
  name: string; // "Meowhattan"
  tagline: string; // one funny line for the intro card
  duration: number; // seconds
  frenzyAt: number; // final frenzy starts when this many seconds are left
  valueMul: number; // global $ multiplier for this city
  world: WorldDef;
  enemies: EnemySpec[];
  boss?: { type: EnemyId; at: number; endsLevel: boolean }; // spawned by the boss type itself at `at` seconds elapsed
  fishTrucks: number; // <= CAPS.fish
  cars: number; // <= CAPS.cars
  people: number; // <= CAPS.people
  wanted: { first: number; every: number; bonus: number; timeBonus: number; minHeight: number };
  objectives: [Objective, Objective, Objective]; // one star each
  unlockStars: number; // total campaign stars needed to unlock (0 for the first city); also needs the previous city cleared (>= 1 star)
  catnipBase: number; // catnip for finishing, before star bonus
  music: MusicSpec;
  tutorial: boolean;
}

// ---------- cats ----------
export interface CatStats {
  walk: number; // 34
  zoom: number; // 62
  turn: number; // rad/s, 7
  radius: number; // collision radius, 13
  headY: number; // head height for enemy aim, 46
  scale: number; // model scale, 1
  swatCd: number; // 0.32
  swatReach: number; // 26 (centre of the strike ahead of the cat)
  swatRadius: number; // 17
  swatPower: number; // $ and knock multiplier, 1
  pounceCd: number; // 2.0
  pounceR: number; // 32
  pounceJump: number; // vy 95
  pounceFwd: number; // 85
  patienceMax: number; // 100
  wetResist: number; // multiplier on patience drain, 1 (lower is tougher)
  stunResist: number; // multiplier on startle seconds, 1
  ultraCharge: number; // multiplier on ULTRA gain, 1
  ultraTime: number; // seconds, 7
}

/** What the core needs from a cat model. Built by CatDef.build(). */
export interface CatRig {
  root: THREE.Group;
  swipe: number; // set to 1 on swat, the rig decays it
  swipeSide: number; // -1 | 1, core flips it each swat
  shake: number; // wet shake 0..1
  squash: number; // landing squash 0..1
  scare: number; // startled (cucumber) 0..1
  ultra: boolean;
  look: number; // -1..1 glance
  animate(dt: number, time: number, speed: number, airborne: boolean): void;
  /** world positions of the two eyes (lasers, glow) */
  eyes(out: THREE.Vector3[]): void;
}

/** A cat's ULTRA ability. Core calls start() when the meter is full and E is pressed, update() every frame while active. */
export interface UltraAbility {
  id: string;
  name: string; // banner text, "LASER EYES!"
  color: string; // banner colour
  tallyLabel: string; // HUD running total label ("ZAP"); G.zap holds the total
  moveMul: number; // movement speed multiplier while active (laser 0.6)
  camWide: boolean; // swing the camera wider while active
  start(): void;
  update(dt: number, t: number): void;
  stop(): void; // called once when time runs out or the level ends
}

/** Optional per-cat passive hooks, called by core/player.ts. */
export interface CatHooks {
  onSwat(x: number, z: number): void;
  onPounceLand(x: number, z: number): void;
}

export interface CatDef {
  id: CatId;
  name: string;
  blurb: string;
  ultraName: string; // label for the ULTRA button / key hint
  voice: number; // meow pitch multiplier (tabby 1, chonk ~0.7, siamese ~1.3)
  color: string; // UI accent colour for menus
  cost: number; // catnip to unlock (0 for tabby)
  base: CatStats;
  build(): CatRig;
  ultra: UltraAbility;
  hooks?: Partial<CatHooks>;
}

// ---------- enemies ----------
export interface SwatHit {
  x: number; // strike centre on the ground plane
  z: number;
  strike: THREE.Vector3; // strike point in the air (y ~ 30 + cat y)
  fwd: THREE.Vector3;
  right: THREE.Vector3;
  side: number;
  radius: number;
  power: number;
}

/** Generic area hit from abilities (belly flop, yowl, dash...). */
export interface Blast {
  x: number;
  z: number;
  r: number;
  power: number; // 1 = a pounce
  dirX?: number; // set for directional blasts (cone/dash), else radial
  dirZ?: number;
  cone?: number; // cos of the half-angle for cone blasts (yowl), omit for a circle
  source: 'swat' | 'pounce' | 'laser' | 'ultra' | 'zoom';
}

/**
 * One enemy kind. Each type manages all of its own instances (pooling, models, AI, spawning from its EnemySpec).
 * Core calls init() once at boot, begin() at every level start for types listed in level.enemies (or level.boss),
 * clear() for all types on level start/attract, update() every frame for begun types.
 */
export interface EnemyType {
  readonly id: EnemyId;
  readonly boss?: boolean;
  init(): void;
  begin(spec: EnemySpec | null, level: LevelDef): void; // spec null for a boss listed only in level.boss
  update(dt: number, t: number): void; // spawn only while game.mode === 'play'
  clear(): void;
  alive(): number;
  onSwat?(hit: SwatHit): void;
  onPounceAir?(p: THREE.Vector3, r: number): void; // cat body while airborne
  onPounceLand?(x: number, z: number, r: number): void;
  onLaser?(p: THREE.Vector3, dir: THREE.Vector3): void; // one beam sample point
  onLaserSweep?(x: number, z: number, ang: number): void; // laser lock-on cone from the cat, world heading `ang`
  onBlast?(b: Blast): void;
  onFrenzy?(): void; // final frenzy: retreat / crash
}

